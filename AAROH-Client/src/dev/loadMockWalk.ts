import { isStorableFrame, parseFrame } from '@/lib/ble/FrameParser';
import { useScanStore } from '@/store/scanStore';

import { MOCK_WALK_FRAMES } from './mockFrames';

/**
 * Loads the bundled demo walk into the scan log, as if the stick had sent it.
 *
 * This exists because the pipeline it feeds is long — frame → parse → scan log → sync →
 * clustering → fields → heat map — and the first link needs two phones and a lot of thumb
 * work to exercise. The rest of the chain does not care where the frames came from, so a
 * button that fills the scan log makes the other five links testable on one device.
 *
 * It is a *rehearsal*, not a shortcut: every frame goes through the same `parseFrame` and
 * `isStorableFrame` gates as a real notification, and lands via the same `record()`. Nothing
 * here writes a `ScannedReading` by hand, so a frame the real stick could not deliver cannot
 * be loaded either, and a regression in the parser fails this path too. The one link it
 * does not cover is reassembly of split notifications, which `npm run verify:frames` tests
 * against the shipped splitter.
 *
 * The frames come from `mockFrames.ts`, generated by `scripts/make-mock-walk.mjs` alongside
 * `test-frames/10-survey-3-fields.txt` — so what this loads and what a second phone would
 * send are the same bytes, and the two cannot drift apart.
 */

export type MockWalkResult = {
  /** Frames newly written to the scan log. */
  stored: number;
  /** Frames already present, from an earlier load. */
  skipped: number;
  /** Frames the parser or the range gate refused — should always be zero. */
  rejected: number;
};

/**
 * Feeds the demo walk into `scanStore`.
 *
 * Async and paced, for two reasons. `record()` persists the whole list on every call, so 90
 * synchronous calls would fire 90 overlapping writes at SecureStore; yielding between frames
 * lets each start in order. And the list visibly fills instead of appearing all at once,
 * which is a fair impression of what a walk actually looks like.
 *
 * Loading twice is a no-op rather than a duplicate: frames already in the log are skipped by
 * their raw text. Without that, a second tap would push the earlier copies past the store's
 * 100-scan cap and quietly evict the start of the walk.
 */
export async function loadMockWalk(): Promise<MockWalkResult> {
  const store = useScanStore.getState();
  const seen = new Set(
    store.items.map((item) => item.raw_frame).filter((raw): raw is string => raw !== null),
  );

  const result: MockWalkResult = { stored: 0, skipped: 0, rejected: 0 };

  for (const text of MOCK_WALK_FRAMES) {
    if (seen.has(text)) {
      result.skipped += 1;
      continue;
    }

    const frame = parseFrame(text);
    if (!frame || !isStorableFrame(frame)) {
      result.rejected += 1;
      continue;
    }

    // `getState()` each time: the store is replaced on every write, and holding the first
    // snapshot would append to a stale list.
    const row = useScanStore.getState().record(frame);
    if (row === null) {
      // Duplicate suppression inside the 1.5 s window. The demo frames are all distinct, so
      // this means something upstream sent the same text twice — worth counting, not hiding.
      result.skipped += 1;
      continue;
    }

    seen.add(text);
    result.stored += 1;
    await new Promise<void>((resolve) => setTimeout(resolve, 0));
  }

  return result;
}
